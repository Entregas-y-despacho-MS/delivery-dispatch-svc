/// <reference types="multer" />
import { Body, Controller, Param, Post, Res, UploadedFile, UseInterceptors } from '@nestjs/common';
import { FileInterceptor } from '@nestjs/platform-express';
import { ApiBearerAuth, ApiBody, ApiConsumes, ApiCreatedResponse, ApiOkResponse, ApiOperation, ApiResponse, ApiTags } from '@nestjs/swagger';
import type { Response } from 'express';
import { CurrentUser } from '../../shared/decorators/current-user.decorator.js';
import { ParseIdPipe } from '../../shared/pipes/index.js';
import { ApiBadRequests, ApiConflict, ApiForbidden, ApiIdParam, ApiNotFound, ApiUnauthorized } from '../../shared/utils/swagger/index.js';
import { DriverOnly } from '../auth/decorators/index.js';
import { MAX_EVIDENCE_FILE_BYTES } from './domain/evidence-file.js';
import { DispatchEvidenceService } from './dispatch-evidence.service.js';
import { DeliveryEvidenceDto } from './dto/delivery-evidence.dto.js';
import { RegisterEvidenceDto } from './dto/register-evidence.dto.js';

/**
 * Error dictionary: VALIDATION_FAILED 400, EVIDENCE_FILE_REQUIRED 400, INVALID_CAPTURE_TIME 400,
 *   INVALID_TOKEN 401, INSUFFICIENT_PERMISSIONS 403, DISPATCH_NOT_FOUND 404,
 *   EVIDENCE_ID_CONFLICT 409, 413 file over 500 KB, UNSUPPORTED_EVIDENCE_FILE_TYPE 415
 */
@ApiTags('Dispatches')
@ApiBearerAuth('access-token')
@Controller('dispatches')
export class DispatchEvidenceController {
    constructor(private readonly service: DispatchEvidenceService) {}

    @Post(':id/evidences')
    @DriverOnly()
    // Without limits multer buffers the whole upload in memory: the cap rejects an oversized file with 413.
    @UseInterceptors(FileInterceptor('file', { limits: { fileSize: MAX_EVIDENCE_FILE_BYTES, files: 1 } }))
    @ApiConsumes('multipart/form-data')
    @ApiIdParam('Dispatch')
    @ApiOperation({
        summary:     'Register a signature or photo evidence',
        description: 'Used by the driver\'s app to upload the proof of delivery of a dispatch on their route. Sent as `multipart/form-data` with the `file` and the fields below. A signature is a PNG and a photo a JPEG, up to 500 KB: 400 for missing or invalid fields, 413 for a bigger file, 415 for another type. The file goes to storage under a UUID name and only its URL is saved. `evidenceId` is the idempotency key: 201 when registered now, 200 with the original record when it was already registered (409 if that id belongs to another dispatch). Registering evidence does not deliver the dispatch: the status change is a separate call. Requires driver role.',
    })
    @ApiBody({
        schema: {
            type:       'object',
            properties: {
                file:             { type: 'string', format: 'binary', description: 'The signature (PNG) or the photo (JPEG), up to 500 KB.' },
                evidenceId:       { type: 'string', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 generated by the device; it is the evidence ID and makes a retry safe.' },
                type:             { type: 'string', enum: ['signature', 'photo'], description: 'Kind of evidence.' },
                capturedAt:       { type: 'string', format: 'date-time', example: '2026-10-18T14:03:00.000Z', description: 'UTC instant of the capture; not in the future.' },
                lat:              { type: 'number', example: -17.783327, description: 'Capture latitude.' },
                lng:              { type: 'number', example: -63.18214, description: 'Capture longitude.' },
                receiverName:     { type: 'string', example: 'Maria Lopez', description: 'Who received the order (3 to 150 characters). Required for a signature.' },
                receiverDocument: { type: 'string', example: '1234567', description: 'ID document of who received the order (up to 30 characters). Required for a signature.' },
            },
            required: ['file', 'evidenceId', 'type', 'capturedAt', 'lat', 'lng'],
        },
    })
    @ApiCreatedResponse({ type: DeliveryEvidenceDto, description: 'The evidence was registered now.' })
    @ApiOkResponse({ type: DeliveryEvidenceDto, description: 'The `evidenceId` was already registered: this is the original record, nothing changed.' })
    @ApiBadRequests({ validation: true, id: true, errors: [{ code: 'EVIDENCE_FILE_REQUIRED', message: 'A photo or signature evidence needs its file.' }, { code: 'INVALID_CAPTURE_TIME', message: 'capturedAt cannot be in the future.' }], example: ['evidenceId must be a UUID', 'receiverName must be longer than or equal to 3 characters'] })
    @ApiUnauthorized({ code: 'INVALID_TOKEN', message: 'Invalid or expired token.' })
    @ApiForbidden({ code: 'INSUFFICIENT_PERMISSIONS', message: 'Dispatch is not assigned to your route.' })
    @ApiNotFound({ code: 'DISPATCH_NOT_FOUND', message: 'Dispatch not found.' })
    @ApiConflict({ code: 'EVIDENCE_ID_CONFLICT', message: 'This evidenceId already belongs to another dispatch.' })
    @ApiResponse({
        status:      413,
        description: 'The file is bigger than 500 KB.',
        schema:      { type: 'object', properties: { statusCode: { type: 'integer', example: 413 }, error: { type: 'string', example: 'HTTP_ERROR' }, message: { type: 'string', example: 'File too large' }, path: { type: 'string', example: '/api/dispatches/42/evidences' }, timestamp: { type: 'string', format: 'date-time', example: '2026-10-18T14:05:00.000Z' } } },
    })
    @ApiResponse({
        status:      415,
        description: 'A signature must be a PNG and a photo a JPEG.',
        schema:      { type: 'object', properties: { statusCode: { type: 'integer', example: 415 }, error: { type: 'string', example: 'UNSUPPORTED_EVIDENCE_FILE_TYPE' }, message: { type: 'string', example: 'The file must be a PNG image.' }, path: { type: 'string', example: '/api/dispatches/42/evidences' }, timestamp: { type: 'string', format: 'date-time', example: '2026-10-18T14:05:00.000Z' } } },
    })
    async register(
        @Param('id', ParseIdPipe) id: number,
        @CurrentUser('id') driverId: number,
        @Body() dto: RegisterEvidenceDto,
        @UploadedFile() file: Express.Multer.File | undefined,
        @Res({ passthrough: true }) response: Response,
    ): Promise<DeliveryEvidenceDto> {
        const { evidence, created } = await this.service.register(id, driverId, dto, file);
        response.status(created ? 201 : 200);
        return evidence;
    }
}
