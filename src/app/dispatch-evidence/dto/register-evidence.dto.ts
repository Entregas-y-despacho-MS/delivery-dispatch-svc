import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import { IsDateString, IsIn, IsNotEmpty, IsNumber, IsString, IsUUID, Max, MaxLength, Min, MinLength, ValidateIf } from 'class-validator';

const trim = ({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim() : value);
// An empty multipart field must not become 0 (Number('') is 0): it stays a string and fails @IsNumber.
const toNumber = ({ value }: { value: unknown }) => (typeof value === 'string' && value.trim() !== '' ? Number(value) : value);
const isSignature = (dto: RegisterEvidenceDto) => dto.type === 'signature';

// Comes from a multipart/form-data body: every field arrives as a string, hence the numeric transform.
export class RegisterEvidenceDto {
    @ApiProperty({ example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 generated by the device. It becomes the evidence record ID, so sending the same one again never duplicates it.' })
    @IsUUID('7')
    evidenceId: string;

    @ApiProperty({ enum: ['signature', 'photo'], description: 'A signature must be a PNG and a photo a JPEG. The OTP evidence is registered by the OTP validation endpoint, not here.' })
    @IsIn(['signature', 'photo'])
    type: 'signature' | 'photo';

    @ApiProperty({ example: '2026-10-18T14:03:00.000Z', description: 'UTC instant when the device captured the evidence. It cannot be in the future.' })
    @IsDateString()
    capturedAt: string;

    @ApiProperty({ type: 'number', format: 'double', minimum: -90, maximum: 90, example: -17.783327, description: 'Latitude where the evidence was captured, up to 6 decimals.' })
    @Transform(toNumber)
    @IsNumber({ maxDecimalPlaces: 6 })
    @Min(-90)
    @Max(90)
    lat: number;

    @ApiProperty({ type: 'number', format: 'double', minimum: -180, maximum: 180, example: -63.18214, description: 'Longitude where the evidence was captured, up to 6 decimals.' })
    @Transform(toNumber)
    @IsNumber({ maxDecimalPlaces: 6 })
    @Min(-180)
    @Max(180)
    lng: number;

    @ApiPropertyOptional({ example: 'Maria Lopez', minLength: 3, maxLength: 150, description: 'Full name of whoever received the order. Required for a signature; ignored for a photo.' })
    @ValidateIf(isSignature)
    @Transform(trim)
    @IsString()
    @MinLength(3)
    @MaxLength(150)
    receiverName?: string;

    @ApiPropertyOptional({ example: '1234567', maxLength: 30, description: 'ID document number of whoever received the order. Required for a signature; ignored for a photo.' })
    @ValidateIf(isSignature)
    @Transform(trim)
    @IsString()
    @IsNotEmpty()
    @MaxLength(30)
    receiverDocument?: string;
}
