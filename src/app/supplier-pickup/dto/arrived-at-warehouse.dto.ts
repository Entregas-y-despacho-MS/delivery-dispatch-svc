import { ApiProperty } from '@nestjs/swagger';
import { IsDateString, IsNumber, IsUUID, Matches, Max, Min } from 'class-validator';

export class ArrivedAtWarehouseDto {
    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a11', description: 'UUID v7 generated by the driver app; idempotency key for this event.' })
    @IsUUID('7')
    eventId!: string;

    @ApiProperty({ format: 'date-time', example: '2026-11-03T16:30:00.000Z', description: 'UTC time when the driver arrived at the destination warehouse.' })
    @IsDateString({ strict: true })
    @Matches(/Z$/, { message: 'occurredAt must be expressed in UTC and end with Z.' })
    occurredAt!: string;

    @ApiProperty({ minimum: -90, maximum: 90, example: -16.5001, description: 'Latitude captured when the driver arrived at the destination warehouse.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-90)
    @Max(90)
    lat!: number;

    @ApiProperty({ minimum: -180, maximum: 180, example: -68.1193, description: 'Longitude captured when the driver arrived at the destination warehouse.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-180)
    @Max(180)
    lng!: number;

    @ApiProperty({ minimum: 0, example: 8.4, description: 'GPS horizontal accuracy in meters.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(0)
    accuracy!: number;
}
