import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { ArrayNotEmpty, IsArray, IsDateString, IsInt, IsOptional, IsString, IsUUID, Matches, MaxLength, Min, ValidateNested } from 'class-validator';
import { SupplierPickupItemDto } from './supplier-pickup-item.dto.js';

export class RegisterSupplierPickupDto {
    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 generated by the driver app; idempotency key for this event.' })
    @IsUUID('7')
    eventId!: string;

    @ApiProperty({ type: [SupplierPickupItemDto], minItems: 1, description: 'Every item expected for this pickup, with the quantity actually received.' })
    @IsArray()
    @ArrayNotEmpty()
    @ValidateNested({ each: true })
    @Type(() => SupplierPickupItemDto)
    items!: SupplierPickupItemDto[];

    @ApiProperty({ minimum: 0, example: 8, description: 'Total boxes the driver received, declared independently of the per-item count.' })
    @IsInt()
    @Min(0)
    receivedBoxes!: number;

    @ApiProperty({ format: 'date-time', example: '2026-11-03T14:03:00.000Z', description: 'UTC time when the driver confirmed the pickup.' })
    @IsDateString({ strict: true })
    @Matches(/Z$/, { message: 'occurredAt must be expressed in UTC and end with Z.' })
    occurredAt!: string;

    @ApiPropertyOptional({ example: 'INC-QTY-MISMATCH', description: 'Code of an active incident reason in the catalog. Required when any item differs from its expected quantity.' })
    @IsOptional()
    @IsString()
    @MaxLength(30)
    reasonCode?: string;

    @ApiPropertyOptional({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 of a photo already uploaded for this dispatch. Required together with reasonCode when any item differs from its expected quantity.' })
    @IsOptional()
    @IsUUID('7')
    photoId?: string;
}
