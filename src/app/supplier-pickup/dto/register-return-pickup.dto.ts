import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsBoolean, IsDateString, IsNumber, IsOptional, IsString, IsUUID, Matches, Max, MaxLength, Min, ValidateNested } from 'class-validator';

export class ReturnPickupChecklistDto {
    @ApiProperty({ example: true, description: 'Point 1: the product comes in its original or an adequate package.' })
    @IsBoolean()
    originalPackaging!: boolean;

    @ApiProperty({ example: true, description: 'Point 2: parts and accessories are complete.' })
    @IsBoolean()
    completeParts!: boolean;

    @ApiProperty({ example: true, description: 'Point 3: the product shows no damage from misuse.' })
    @IsBoolean()
    noMisuseDamage!: boolean;
}

export class RegisterReturnPickupDto {
    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a20', description: 'UUID v7 generated by the driver app; idempotency key for this event.' })
    @IsUUID('7')
    eventId!: string;

    @ApiProperty({ type: ReturnPickupChecklistDto, description: 'Physical inspection checklist of 3 points. Leaving any point unchecked makes observations mandatory.' })
    @ValidateNested()
    @Type(() => ReturnPickupChecklistDto)
    checklist!: ReturnPickupChecklistDto;

    @ApiPropertyOptional({ maxLength: 1000, example: 'Caja con golpes, sin manual de usuario.', description: 'Free-text inspection notes. Required (not blank) when any checklist point is unchecked.' })
    @IsOptional()
    @IsString()
    @MaxLength(1000)
    observations?: string;

    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a21', description: 'UUID v7 of a photo evidence of the product already uploaded for this dispatch (ST-31.3).' })
    @IsUUID('7')
    photoId!: string;

    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a22', description: "UUID v7 of the customer's signature evidence already uploaded for this dispatch (ST-31.3)." })
    @IsUUID('7')
    signatureId!: string;

    @ApiProperty({ format: 'date-time', example: '2026-11-07T14:03:00.000Z', description: 'UTC time when the customer signed the pickup.' })
    @IsDateString({ strict: true })
    @Matches(/Z$/, { message: 'occurredAt must be expressed in UTC and end with Z.' })
    occurredAt!: string;

    @ApiProperty({ type: 'number', format: 'double', minimum: -90, maximum: 90, example: -16.5001, description: 'Latitude captured when the pickup was confirmed.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-90)
    @Max(90)
    lat!: number;

    @ApiProperty({ type: 'number', format: 'double', minimum: -180, maximum: 180, example: -68.1193, description: 'Longitude captured when the pickup was confirmed.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-180)
    @Max(180)
    lng!: number;

    @ApiProperty({ type: 'number', format: 'double', minimum: 0, example: 8.4, description: 'GPS horizontal accuracy in meters.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(0)
    accuracy!: number;
}
