import { ApiProperty } from '@nestjs/swagger';
import { IsDateString, IsIn, IsNumber, IsUUID, Matches, Max, Min } from 'class-validator';

export const DRIVER_DISPATCH_STATUS = {
    IN_TRANSIT:    'in_transit',
    DELIVERED:     'delivered',
    NOT_DELIVERED: 'not_delivered',
} as const;

export type DriverDispatchStatus = typeof DRIVER_DISPATCH_STATUS[keyof typeof DRIVER_DISPATCH_STATUS];

export class UpdateDispatchStatusDto {
    @ApiProperty({ enum: Object.values(DRIVER_DISPATCH_STATUS), example: DRIVER_DISPATCH_STATUS.IN_TRANSIT, description: 'New status by name. Route start (`out_for_delivery`) is handled by ST-51.5; incident reporting uses its dedicated endpoint.' })
    @IsIn(Object.values(DRIVER_DISPATCH_STATUS), { message: "status must be one of: in_transit, delivered, not_delivered." })
    status!: DriverDispatchStatus;

    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 generated by the mobile app; idempotency key.' })
    @IsUUID('7')
    eventId!: string;

    @ApiProperty({ format: 'date-time', example: '2026-10-14T14:03:00.000Z', description: 'UTC time when the driver performed the transition.' })
    @IsDateString({ strict: true })
    @Matches(/Z$/, { message: 'occurredAt must be expressed in UTC and end with Z.' })
    occurredAt!: string;

    @ApiProperty({ minimum: -90, maximum: 90, example: -16.5001, description: 'Latitude captured when the driver performed the transition.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-90)
    @Max(90)
    lat!: number;

    @ApiProperty({ minimum: -180, maximum: 180, example: -68.1193, description: 'Longitude captured when the driver performed the transition.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-180)
    @Max(180)
    lng!: number;

    @ApiProperty({ minimum: 0, example: 8.4, description: 'GPS horizontal accuracy in meters.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(0)
    accuracy!: number;
}
