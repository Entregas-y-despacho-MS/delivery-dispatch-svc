import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsDateString, IsNumber, IsOptional, IsString, IsUUID, Max, MaxLength, Matches, Min } from 'class-validator';

export class CreateDispatchIncidentDto {
    @ApiProperty({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 generated by the driver app; it is the idempotency key for this incident.' })
    @IsUUID('7')
    incidentId!: string;

    @ApiProperty({ example: 'INC-CUST-ABSENT', description: 'Code of an active incident reason in the catalog.' })
    @IsString()
    @MaxLength(30)
    reasonCode!: string;

    @ApiProperty({ minLength: 1, maxLength: 1000, example: 'No one answered at the delivery address.', description: 'Driver observations. Required for every reason; at least 10 characters when the reason is Other/Otro.' })
    @IsString()
    @MaxLength(1000)
    @Matches(/\S/, { message: 'observations must not be blank.' })
    observations!: string;

    @ApiProperty({ format: 'date-time', example: '2026-10-19T14:03:00.000Z', description: 'UTC time when the incident happened on the device; no more than 30 days old or 1 hour in the future.' })
    @IsDateString({ strict: true })
    @Matches(/Z$/, { message: 'occurredAt must be expressed in UTC and end with Z.' })
    occurredAt!: string;

    @ApiProperty({ minimum: -90, maximum: 90, example: -16.5001, description: 'Latitude captured when the incident happened.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-90)
    @Max(90)
    lat!: number;

    @ApiProperty({ minimum: -180, maximum: 180, example: -68.1193, description: 'Longitude captured when the incident happened.' })
    @IsNumber({ allowNaN: false, allowInfinity: false })
    @Min(-180)
    @Max(180)
    lng!: number;

    @ApiPropertyOptional({ format: 'uuid', example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10', description: 'UUID v7 of a photo already uploaded for this dispatch. Required when the reason requires evidence, except for INC-COMP-FAILURE.' })
    @IsOptional()
    @IsUUID('7')
    evidenceId?: string;
}
