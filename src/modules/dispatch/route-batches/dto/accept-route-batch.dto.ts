import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsIn,
  IsInt,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { INT4_MAX } from '../../../../shared/constants/int4.js';

export const COTEJO_FAILURE_REASONS = [
  'missing',
  'damaged',
  'does_not_fit',
] as const;
export type CotejoFailureReason = (typeof COTEJO_FAILURE_REASONS)[number];

export class CotejoFailureDto {
  @ApiProperty({
    type: 'integer',
    minimum: 1,
    maximum: INT4_MAX,
    example: 101,
    description:
      'Dispatch (stop) of the batch that holds the failed package. The whole stop does not leave on the route until it is resolved, even if only one of its packages failed.',
  })
  @IsInt()
  @Min(1)
  @Max(INT4_MAX)
  dispatchId!: number;

  @ApiProperty({
    minLength: 1,
    maxLength: 100,
    example: 'PKG-101-A',
    description:
      'External ID of the package that failed the check; it must belong to the dispatch. Each package is reported at most once; a stop with two failed packages sends two failures, each with its own reason and photo.',
  })
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  packageId!: string;

  @ApiProperty({
    enum: COTEJO_FAILURE_REASONS,
    example: 'damaged',
    description:
      'Why the package failed the check: it is missing, arrived damaged or does not fit in the vehicle.',
  })
  @IsIn(COTEJO_FAILURE_REASONS)
  reason!: CotejoFailureReason;

  @ApiPropertyOptional({
    maxLength: 500,
    example: 'Box crushed on one corner.',
    description: 'Free text with more detail about the failure.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  detail?: string;

  @ApiProperty({
    format: 'uuid',
    example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a10',
    description:
      'The `photoId` returned by `POST /route-batches/:id/cotejo-photos` for this same batch. The photo is mandatory.',
  })
  @IsUUID('7')
  photoId!: string;
}

export class AcceptRouteBatchDto {
  @ApiProperty({
    format: 'uuid',
    example: '01933b6e-7f2a-7c3d-9a1b-2f8e6c4d5a11',
    description:
      'UUID v7 generated by the driver app; retries with the same eventId do not accept the batch twice.',
  })
  @IsUUID('7')
  eventId!: string;

  @ApiPropertyOptional({
    type: [CotejoFailureDto],
    maxItems: 200,
    description:
      'Packages that failed the physical check. Omit it or send an empty list when every package matches.',
  })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(200)
  @ValidateNested({ each: true })
  @Type(() => CotejoFailureDto)
  failures?: CotejoFailureDto[];
}
