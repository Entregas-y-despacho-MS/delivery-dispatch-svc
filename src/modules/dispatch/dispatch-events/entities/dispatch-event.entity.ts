import { Column, Entity, JoinColumn, ManyToOne, PrimaryGeneratedColumn } from 'typeorm';
import { BaseCreated } from '../../../../database/entities/base.entity.js';
import { Dispatch } from '../../dispatches/entities/dispatch.entity.js';
import { User } from '../../../auth/users/entities/user.entity.js';

// Append-only log — a recorded event is never modified, no updatedAt.
@Entity('dispatch_events')
export class DispatchEvent extends BaseCreated {
    @PrimaryGeneratedColumn({ name: 'dispatch_event_id' })
    id: number;

    @Column({ name: 'dispatch_id', type: 'int' })
    dispatchId: number;

    // created | assigned | status_changed | ...
    @Column({ name: 'event_type', type: 'varchar', length: 50 })
    eventType: string;

    @Column({ name: 'detail', type: 'text', nullable: true })
    detail: string | null;

    @Column({ name: 'actor_user_id', type: 'int', nullable: true })
    actorUserId: number | null;

    @Column({ name: 'actor_type', type: 'varchar', length: 20, nullable: true })
    actorType: string | null;

    @Column({ name: 'reason', type: 'text', nullable: true })
    reason: string | null;

    @Column({ name: 'metadata', type: 'jsonb', nullable: true })
    metadata: Record<string, unknown> | null;

    // Id generated by the driver's mobile app when the event was created offline (RF-U13) — the
    // idempotency key for sync retries. NULL for events the backend generates itself.
    @Column({ name: 'client_event_id', type: 'uuid', nullable: true })
    clientEventId: string | null;

    @ManyToOne(() => Dispatch)
    @JoinColumn({ name: 'dispatch_id' })
    dispatch: Dispatch;

    @ManyToOne(() => User)
    @JoinColumn({ name: 'actor_user_id' })
    actorUser: User | null;
}
